#!/usr/bin/env python3
"""Bundle js/*.js into app.js (load order matters). Run after editing any file in js/."""
import pathlib
ORDER = ['core', 'view', 'actions', 'picker', 'notes', 'data', 'image', 'main']
root = pathlib.Path(__file__).parent
out = '/* generated by build.py — edit files in js/ and rebuild */\n' + ''.join(
    f'\n/* ===== js/{n}.js ===== */\n' + (root / 'js' / f'{n}.js').read_text() for n in ORDER)
(root / 'app.js').write_text(out)
print(f'app.js {len(out)//1024} KB')
